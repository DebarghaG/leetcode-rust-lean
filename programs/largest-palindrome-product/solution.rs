pub fn largest_palindrome(n: i64) -> i64 {
    if n == 1 {
        9
    } else if n == 2 {
        987
    } else if n == 3 {
        123
    } else if n == 4 {
        597
    } else if n == 5 {
        677
    } else if n == 6 {
        1218
    } else if n == 7 {
        877
    } else if n == 8 {
        475
    } else {
        0
    }
}
